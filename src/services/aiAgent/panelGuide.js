// ---------- جست‌وجو ----------
const norm = (s) => String(s || '')
  .normalize('NFKC')
  .replace(/[يى]/g, 'ی').replace(/ك/g, 'ک').replace(/[أإآ]/g, 'ا').replace(/ؤ/g, 'و')
  .replace(/[ً-ٰٟـ]/g, '').replace(/[​-‏‪-‮⁠﻿]/g, ' ')
  .replace(/[^\p{L}\p{N}\s]/gu, ' ').replace(/\s+/g, ' ').trim().toLowerCase();

const STOP = new Set(['در', 'از', 'به', 'را', 'که', 'این', 'آن', 'و', 'با', 'برای', 'چطور', 'چگونه', 'کجاست', 'کجا', 'چی', 'چیه', 'کجا', 'هست', 'میشه', 'می', 'شه', 'پنل', 'کنم', 'کنیم', 'بکنم', 'رو', 'یه', 'یک', 'من', 'ما', 'بگو', 'بده', 'وجود', 'دارد', 'دارم']);

function rolesOf(perm) {
  if (!perm) return ROLES.map((r) => ROLE_FA[r]);
  return ROLES.filter((r) => hasPermission(r, perm)).map((r) => ROLE_FA[r]);
}

function scoreEntry(e, tokens, whole) {
  const hay = { title: norm(e.title), kw: e.kw.map(norm), what: norm(e.what), path: norm(e.path), how: norm((e.how || []).join(' ')) };
  let s = 0;
  for (const k of hay.kw) { if (whole && k.length >= 4 && (whole.includes(k) || (whole.length >= 4 && k.includes(whole)))) s += 6; }
  for (const t of tokens) {
    if (hay.kw.some((k) => k.split(' ').includes(t))) s += 3;
    else if (hay.kw.some((k) => k.includes(t))) s += 2;
    if (hay.title.includes(t)) s += 3;
    if (hay.path.includes(t)) s += 1;
    if (hay.what.includes(t) || hay.how.includes(t)) s += 1;
  }
  return s;
}

function present(e) {
  const out = { id: e.id, title: e.title, where: e.path, kind: e.ui === 'panel' ? 'صفحه/قابلیت پنل' : e.ui === 'bot' ? 'بات تلگرام / ورود' : 'فقط API (در پنل صفحه ندارد)', who: rolesOf(e.perm), what: e.what };
  if (e.how && e.how.length) out.how = e.how;
  return out;
}

/** بدون query ⇒ فهرست همه‌ی صفحه‌ها؛ با query ⇒ بهترین مطابقت‌ها (حداکثر ۴) */
function search(query) {
  const q = norm(query);
  if (!q) {
    const groups = {};
    for (const e of ENTRIES.filter((x) => x.ui === 'panel' && x.path.startsWith('منوی کناری'))) {
      const m = /گروه «([^»]+)» ← «([^»]+)»/.exec(e.path);
      if (m) (groups[m[1]] = groups[m[1]] || []).push(m[2]);
    }
    return { menu: groups, note: 'منوی کناری پنل به این گروه‌ها تقسیم می‌شود؛ هر کاربر فقط صفحه‌هایی را می‌بیند که مجوزش را دارد. برای جزئیات هر مورد query بدهید (مثلاً «حقوق»، «افزودن کارمند»، «اعتراض»).', others: ENTRIES.filter((x) => !(x.ui === 'panel' && x.path.startsWith('منوی کناری'))).map((x) => x.title) };
  }
  const tokens = q.split(' ').filter((t) => t.length > 1 && !STOP.has(t));
  const ranked = ENTRIES.map((e) => ({ e, s: scoreEntry(e, tokens, q) })).filter((x) => x.s >= 3).sort((a, b) => b.s - a.s).slice(0, 4);
  if (!ranked.length) return { matches: [], note: 'در راهنمای پنل مورد مرتبطی پیدا نشد. با query خالی فهرست صفحه‌ها را ببین؛ اگر باز هم نبود، صریحاً بگو در پنل چنین قابلیتی پیدا نشد و حدس نزن.' };
  return { matches: ranked.map((x) => present(x.e)) };
}

